constexpr std::size_t TrackCount = 8;

enum class InstrumentType : std::uint8_t {
    Sampler,
    Synth
};

struct AdEnvelopeSettings {
    static constexpr float MinAttackSeconds = 0.001F;
    static constexpr float MaxAttackSeconds = 0.25F;
    static constexpr float MinDecaySeconds = 0.02F;
    static constexpr float MaxDecaySeconds = 4.0F;

    float attackSeconds = 0.005F;
    float decaySeconds = 0.45F;
};

struct TrackFilterSettings {
    static constexpr float MinCutoffHz = 100.0F;
    static constexpr float MaxCutoffHz = 20000.0F;

    bool enabled = false;
    float cutoffHz = 12000.0F;
};

enum class SynthEngineType : std::uint8_t {
    BasicVa,
    Plaits
};

struct TrackSynthSettings {
    static constexpr float MinPitchHz = 20.0F;
    static constexpr float MaxPitchHz = 2000.0F;
    static constexpr int ModelCount = 16;

    SynthEngineType engineType = SynthEngineType::BasicVa;
    // Selected Plaits model. morph stays a continuous parameter inside it.
    std::uint8_t model = 0;
    float pitchHz = 110.0F;
    float morph = 0.5F;
    float timbre = 0.5F;
    float color = 0.5F;
};

struct TrackState {
    EuclideanConfig rhythm{};
    EffectiveRhythm effectiveRhythm{};
    std::array<LfoConfig, MaxLfosPerTrack> lfos{};
    JitterConfig jitter{};
    TuringConfig turing{};
    // Runtime-only counter so the UI can ask the audio thread for a fresh
    // register without changing any persisted parameter.
    std::uint32_t turingReseedRevision = 0;
    std::uint8_t position = 0;
    bool muted = false;
    InstrumentType instrument = InstrumentType::Sampler;
    std::uint8_t volume = 100;
    float pan = 0.0F;
    float reverbSend = 0.0F;
    float delaySend = 0.0F;
    AdEnvelopeSettings envelope{};
    TrackFilterSettings filter{};
    TrackSynthSettings synth{};
};

struct TickResult {
    std::array<bool, TrackCount> triggered{};
    std::array<std::uint8_t, TrackCount> stepPositions{};
    // Per-track semitone offset generated by the Turing machine. Zero means
    // the track plays at its base pitch.
    std::array<std::int8_t, TrackCount> pitchOffsets{};
    std::uint64_t masterTickPosition = 0;
    bool valid = true;
};

